#!/bin/bash
# Stage 2: render EC2 user data from the resolved config.
#
# The output writes server.env and the server/ scripts from this checkout into
# the server directory, then runs setup.sh. Embedding the scripts means local
# edits take effect without pushing; only the mods are downloaded.

USERDATA_LIMIT=16384
EMBEDDED_FILES=(common.sh start.sh stop.sh newworld.sh setup.sh)
HEREDOC_END="MC_LAUNCH_EOF"

# The console only takes plain text, so warn when --render-only output won't fit.
check_console_size() {
    local size
    size=$(wc -c)
    if [ "$size" -gt "$USERDATA_LIMIT" ]; then
        warn "This is $size bytes, over the console's $USERDATA_LIMIT-byte limit. Paste the gzipped, base64 version instead and tick 'already base64-encoded':"
        warn "  bin/mc launch --render-only ... | gzip -9 | base64 -w0"
    fi
}

render_userdata() {
    local f content
    cat <<HEADER
#!/bin/bash
# Generated by bin/mc launch for '${NAME}' (profile: ${PROFILE}).
# Re-render with \`bin/mc launch --render-only\` instead of editing.
set -e
SERVER_DIR=/home/ubuntu/minecraft
mkdir -p "\$SERVER_DIR"

cat > "\$SERVER_DIR/server.env" <<'${HEREDOC_END}'
HEADER
    write_server_env
    echo "$HEREDOC_END"

    for f in "${EMBEDDED_FILES[@]}"; do
        content=$(tr -d '\r' < "$REPO_ROOT/server/$f")
        [[ $'\n'"$content"$'\n' != *$'\n'"$HEREDOC_END"$'\n'* ]] \
            || die "server/$f contains the line $HEREDOC_END, which ends the embedded file early."
        printf '\ncat > "$SERVER_DIR/%s" <<'"'"'%s'"'"'\n' "$f" "$HEREDOC_END"
        printf '%s\n' "$content"
        echo "$HEREDOC_END"
    done

    printf '\nexec bash "$SERVER_DIR/setup.sh"\n'
}
